export type MessageKey = keyof typeof messageCatalog

const SUPPORTED_LANGUAGES = LANGUAGE_PREFERENCES.filter(
  (preference): preference is SupportedLanguage => preference !== 'system',
)

export const MESSAGE_KEYS = Object.keys(messageCatalog) as MessageKey[]

export const translationResources = Object.fromEntries(
  SUPPORTED_LANGUAGES.map((language) => [
    language,
    {
      translation: Object.fromEntries(
        MESSAGE_KEYS.map((key) => [key, messageCatalog[key][language]]),
      ) as Record<MessageKey, string>,
    },
  ]),
) as Record<SupportedLanguage, { translation: Record<MessageKey, string> }>
